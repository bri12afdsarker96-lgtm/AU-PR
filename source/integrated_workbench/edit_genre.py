def genre_names() -> list[str]:
    return list(GENRE_PRESETS.keys())


def get_preset(genre: str) -> GenrePreset:
    return GENRE_PRESETS.get(genre, GENRE_PRESETS[DEFAULT_GENRE])


def apply_genre(settings, genre: str):
    """把赛道画风铺到 AutoCutSettings（就地返回同一对象，便于链式）。"""
    preset = get_preset(genre)
    settings.filter_name = preset.filter_name
    settings.effect_names = list(preset.effects)
    settings.transition_name = preset.transition
    settings.subtitle_style = preset.subtitle_style
    settings.clip_seconds = preset.pace_seconds
    return settings
